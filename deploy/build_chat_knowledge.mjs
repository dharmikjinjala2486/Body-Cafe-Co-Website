/* Builds what the store assistant knows about the shop from the Help Centre and the five policies
   (web/support-content.js, the single source of those facts) and writes it to
   supabase/functions/operations/chat-knowledge.js, which the hosted API imports and app/chat.py reads.
   Run after changing web/support-content.js:   node deploy/build_chat_knowledge.mjs
   `--check` exits 1 when the written file is out of date (used by deploy/supabase-tests/test-chat.mjs). */
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';

const root = new URL('..', import.meta.url);
const target = new URL('supabase/functions/operations/chat-knowledge.js', root);

export function buildKnowledge() {
  const window = {};
  vm.runInNewContext(readFileSync(new URL('web/support-content.js', root), 'utf8'), {window});
  const S = window.BCCSupportContent, B = S.BUSINESS, out = [];
  const flat = v => Array.isArray(v) ? v.map(flat).filter(Boolean).join(' ') : v && typeof v === 'object' ? flat(Object.values(v).filter(x => typeof x !== 'boolean')) : typeof v === 'string' ? v.replace(/<[^>]+>/g, '').trim() : '';
  out.push('# The business',
    `Brand: ${B.brand} Sold by ${B.legalName}`,
    `Registered office: ${B.address}.`,
    `GSTIN ${B.gstin}. FSSAI licence ${B.fssai}.`,
    `Support hours: ${B.hours}. First reply: ${B.response}.`,
    'Ways to reach support: ' + Object.values(B.channels).filter(c => c.live).map(c => `${c.label} (${c.detail})`).join('; ') + '. The contact form is at /contact.',
    `Grievance officer: ${B.grievanceOfficer}.`, '');
  out.push('# Help Centre answers (the page for each is given beside it)');
  for (const cat of S.CATEGORIES) {
    out.push('', `## ${cat.title}`);
    for (const a of S.ARTICLES.filter(x => x.cat === cat.id)) {
      out.push(`Q: ${a.title} (/help/${a.cat}/${a.id})`, `A: ${[a.answer, flat(a.body)].filter(Boolean).join(' ')}`);
      const links = (a.actions || []).filter(x => x.href && x.href.startsWith('/')).map(x => `${x.label}: ${x.href}`);
      if (links.length) out.push('Useful pages: ' + links.join('; '));
    }
  }
  out.push('', `# Policies (${S.DOCS.version}, updated ${S.DOCS.updated})`);
  for (const p of Object.values(S.POLICIES)) {
    out.push('', `## ${p.title} (${p.path})`, 'In short: ' + flat(p.summary));
    for (const s of p.sections || []) out.push(`### ${s.h} (${p.path}#${s.id})`, flat(Object.entries(s).filter(([k]) => !['id', 'h'].includes(k)).map(([, v]) => v)));
  }
  return out.join('\n');
}

const file = text => '/* Generated by deploy/build_chat_knowledge.mjs from web/support-content.js. Do not edit by hand. */\nexport const STORE_KNOWLEDGE = ' + JSON.stringify(text) + ';\n';

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = file(buildKnowledge());
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(target, 'utf8'); } catch {}
    if (now !== next) { console.error('chat-knowledge.js is out of date. Run: node deploy/build_chat_knowledge.mjs'); process.exit(1); }
    console.log('chat-knowledge.js is up to date.');
  } else {
    writeFileSync(target, next);
    console.log('Wrote chat-knowledge.js (' + next.length + ' characters).');
  }
}
